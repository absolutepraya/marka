import { and, eq } from "drizzle-orm";

import { definePersist } from "@karakeep/db/persist";
import {
  assets,
  AssetTypes,
  bookmarks,
  bookmarkTranscripts,
} from "@karakeep/db/schema";

/**
 * Saves a new transcript source for a bookmark: the generated transcript or
 * the selected YouTube caption track, and optionally the caption files.
 *
 * The existing row is read inside the transaction, so a manual transcript
 * edit saved while the job ran is never overwritten. When `captionAssets` is
 * non-empty it replaces the bookmark's caption source rows; the caller
 * deletes the old files after this commits.
 */
export const saveTranscriptSource = definePersist<
  {
    bookmarkId: string;
    userId: string;
    provider: "youtube" | "azure-speech";
    providerItemId: string;
    sourceTranscript: string;
    sourceLanguage: string | null;
    sourceIsAutoGenerated: boolean;
    selectedTrackId: string;
    sourceFingerprint: string;
    sourceAttachmentsStatus: "ready" | "partial" | "failed";
    statusMessage: string | null;
    shouldSummarize: boolean;
    captionAssets?: {
      assetId: string;
      size: number;
      contentType: string;
      fileName: string;
    }[];
  },
  { sourceChanged: boolean; manualOverride: boolean; nextRevision: number }
>("transcripts.saveTranscriptSource", (db, input) =>
  db.transaction(async (tx) => {
    const transcript = await tx.query.bookmarkTranscripts.findFirst({
      where: and(
        eq(bookmarkTranscripts.bookmarkId, input.bookmarkId),
        eq(bookmarkTranscripts.provider, input.provider),
      ),
    });
    if (!transcript) {
      throw new Error("Transcript row disappeared during processing");
    }

    const sourceChanged =
      transcript.sourceFingerprint !== input.sourceFingerprint;
    const manualOverride = transcript.manualOverride;
    const nextRevision = sourceChanged
      ? transcript.revision + (manualOverride ? 0 : 1)
      : transcript.revision;

    if (input.captionAssets && input.captionAssets.length > 0) {
      await tx
        .delete(assets)
        .where(
          and(
            eq(assets.bookmarkId, input.bookmarkId),
            eq(assets.assetType, AssetTypes.CAPTION_SOURCE),
          ),
        );
      await tx.insert(assets).values(
        input.captionAssets.map((caption) => ({
          id: caption.assetId,
          assetType: AssetTypes.CAPTION_SOURCE,
          size: caption.size,
          contentType: caption.contentType,
          fileName: caption.fileName,
          bookmarkId: input.bookmarkId,
          transcriptId: transcript.id,
          userId: input.userId,
        })),
      );
    }

    await tx
      .update(bookmarkTranscripts)
      .set({
        providerItemId: input.providerItemId,
        status: "ready",
        statusMessage: input.statusMessage,
        sourceAttachmentsStatus: input.sourceAttachmentsStatus,
        selectedTrackId: input.selectedTrackId,
        sourceLanguage: input.sourceLanguage,
        sourceIsAutoGenerated: input.sourceIsAutoGenerated,
        sourceTranscript: input.sourceTranscript,
        text: manualOverride ? transcript.text : input.sourceTranscript,
        manualOverride,
        revision: nextRevision,
        sourceFingerprint: input.sourceFingerprint,
        sourceFetchedAt: new Date(),
        modifiedAt: new Date(),
      })
      .where(eq(bookmarkTranscripts.id, transcript.id));

    if (sourceChanged && !manualOverride) {
      const bookmarkRow = await tx.query.bookmarks.findFirst({
        where: eq(bookmarks.id, input.bookmarkId),
        columns: { summaryProvenance: true },
      });
      if (bookmarkRow?.summaryProvenance !== "manual") {
        await tx
          .update(bookmarks)
          .set({
            summaryProvenance: "transcript",
            summaryStale: true,
            summarizationStatus: input.shouldSummarize ? "pending" : null,
            modifiedAt: new Date(),
          })
          .where(eq(bookmarks.id, input.bookmarkId));
      }
    }

    return { sourceChanged, manualOverride, nextRevision };
  }),
);
