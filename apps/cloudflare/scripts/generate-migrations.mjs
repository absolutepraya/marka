// Bundles packages/db/drizzle into a module the Durable Object can import,
// because Workers cannot read migration files from disk at runtime.
//
// Durable Object SQLite rejects some statements used by historical
// migrations (0084 creates a TEMPORARY table). Fresh Cloudflare installs
// therefore start from a baseline: the schema produced by applying every
// migration up to BASELINE_THROUGH_IDX with SQLite in Node. Later migrations
// are bundled individually and must be Durable Object compatible.
//
// Usage: node scripts/generate-migrations.mjs [--check]
import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const Database = require("better-sqlite3");

// Pinned: moving it changes what fresh Cloudflare installs run.
const BASELINE_THROUGH_IDX = 98;

// Statements Durable Object SQLite rejects or that conflict with its
// transaction handling.
const FORBIDDEN = [
  /\bCREATE\s+TEMP(ORARY)?\s+(TABLE|VIEW|TRIGGER)\b/i,
  /\bPRAGMA\s+foreign_keys\b/i,
  /^\s*(BEGIN|COMMIT|END|ROLLBACK|SAVEPOINT|RELEASE)\b/i,
  /^\s*(ATTACH|DETACH)\b/i,
];

const here = path.dirname(fileURLToPath(import.meta.url));
const drizzleDir = path.resolve(here, "../../../packages/db/drizzle");
const outFile = path.resolve(
  here,
  "../src/libraryStore/migrations.generated.ts",
);

const journal = JSON.parse(
  await readFile(path.join(drizzleDir, "meta/_journal.json"), "utf8"),
);
const readMigration = (entry) =>
  readFile(path.join(drizzleDir, `${entry.tag}.sql`), "utf8");
const statementsOf = (text) =>
  text
    .split("--> statement-breakpoint")
    .map((statement) => statement.trim())
    .filter(Boolean);

const baselineEntries = journal.entries.filter(
  (entry) => entry.idx <= BASELINE_THROUGH_IDX,
);
const laterEntries = journal.entries.filter(
  (entry) => entry.idx > BASELINE_THROUGH_IDX,
);

const sqlite = new Database(":memory:");
for (const entry of baselineEntries) {
  for (const statement of statementsOf(await readMigration(entry))) {
    sqlite.exec(statement);
  }
}
const baselineStatements = sqlite
  .prepare(
    `SELECT sql FROM sqlite_master
     WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
     ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, rowid`,
  )
  .all()
  .map((row) => row.sql);
sqlite.close();

const problems = [];
const migrations = {};
for (const entry of laterEntries) {
  const text = await readMigration(entry);
  for (const statement of statementsOf(text)) {
    if (FORBIDDEN.some((pattern) => pattern.test(statement))) {
      problems.push(`${entry.tag}: ${statement.slice(0, 120)}`);
    }
  }
  migrations[`m${String(entry.idx).padStart(4, "0")}`] = text;
}
if (problems.length > 0) {
  console.error(
    "These migrations use statements Durable Object SQLite rejects:\n" +
      problems.map((problem) => `  ${problem}`).join("\n"),
  );
  process.exit(1);
}

const pick = ({ idx, when, tag, breakpoints }) => ({
  idx,
  when,
  tag,
  breakpoints,
});
const bundle = {
  baseline: {
    statements: baselineStatements,
    applied: baselineEntries.map((entry) => entry.when),
  },
  journal: { entries: laterEntries.map(pick) },
  migrations,
};

const content = `// Generated by scripts/generate-migrations.mjs from packages/db/drizzle.
// Do not edit; run \`pnpm --filter @karakeep/cloudflare generate:migrations\`.

export interface MigrationBundle {
  /** Schema after migrations 0000 to ${String(BASELINE_THROUGH_IDX).padStart(4, "0")}, for fresh installs. */
  baseline: { statements: string[]; applied: number[] };
  journal: {
    entries: { idx: number; when: number; tag: string; breakpoints: boolean }[];
  };
  migrations: Record<string, string>;
}

const bundle: MigrationBundle = ${JSON.stringify(bundle, null, 2)};

export default bundle;
`;

// Format with the repository's formatter so reformatting is a no-op.
async function formatted(text) {
  const dir = await mkdtemp(path.join(os.tmpdir(), "marka-migrations-"));
  const file = path.join(dir, "migrations.generated.ts");
  try {
    await writeFile(file, text);
    execFileSync(
      path.resolve(here, "../../../node_modules/.bin/oxfmt"),
      ["--config", path.resolve(here, "../../../.oxfmtrc.json"), file],
      { stdio: "ignore" },
    );
    return await readFile(file, "utf8");
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

const output = await formatted(content);

if (process.argv.includes("--check")) {
  const current = await readFile(outFile, "utf8").catch(() => "");
  if (current !== output) {
    console.error(
      "migrations.generated.ts is stale. Run `pnpm --filter @karakeep/cloudflare generate:migrations`.",
    );
    process.exit(1);
  }
  console.log("migrations.generated.ts is up to date.");
} else {
  await writeFile(outFile, output);
  console.log(
    `Wrote a baseline through ${baselineEntries.length} migrations and ${laterEntries.length} later migrations.`,
  );
}
